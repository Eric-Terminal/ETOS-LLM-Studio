    public func generateForScheduledDeliveryIfNeeded(
        reminderEnabled: Bool,
        deliveryTimes: [DailyPulseDeliveryTime],
        referenceDate: Date = Date()
    ) async {
        await waitForPersistedStateLoad()
        guard isDailyPulseEnabled else { return }

        let todayKey = Self.dayKey(for: referenceDate)
        if Self.shouldProcessScheduledDelivery(
            reminderEnabled: reminderEnabled,
            deliveryTimes: deliveryTimes,
            referenceDate: referenceDate,
            lastDeliveryAttemptDayKey: lastDeliveryAttemptDayKey
        ) {
            if Self.shouldUseExistingRunForScheduledDelivery(
                todayRunDayKey: todayRun?.dayKey,
                referenceDate: referenceDate
            ) {
                await DailyPulseDeliveryCoordinator.shared.refreshReminderSchedule(referenceDate: referenceDate)
            } else {
                let shouldNotifyReady = !DailyPulseDeliveryCoordinator.hasFutureDeliveryTime(
                    dayKey: todayKey,
                    deliveryTimes: deliveryTimes,
                    referenceDate: referenceDate
                )
                await generate(
                    force: false,
                    trigger: .delivery,
                    targetDayKey: todayKey,
                    notifyReadyWhenFinished: shouldNotifyReady
                )
            }

            if runs.contains(where: { $0.dayKey == todayKey }) {
                lastDeliveryAttemptDayKey = todayKey
                Self.save(todayKey, forKey: Self.lastDeliveryAttemptDayKeyDefaultsKey, defaults: defaults)
            }
        }

        await generateTomorrowForDeliveryIfNeeded(
            reminderEnabled: reminderEnabled,
            referenceDate: referenceDate
        )
    }

    @discardableResult
    public func generateForBackgroundDeliveryIfNeeded(
        reminderEnabled: Bool,
        deliveryTimes: [DailyPulseDeliveryTime],
        referenceDate: Date = Date()
    ) async -> Bool {
        await waitForPersistedStateLoad()
        guard isDailyPulseEnabled else { return false }
        guard reminderEnabled else { return false }

        let todayKey = Self.dayKey(for: referenceDate)
        let hasTodayRun = runs.contains(where: { $0.dayKey == todayKey })
        if hasTodayRun {
            let tomorrowKey = Self.nextDayKey(from: referenceDate)
            if !runs.contains(where: { $0.dayKey == tomorrowKey }) {
                await generate(
                    force: false,
                    trigger: .delivery,
                    targetDayKey: tomorrowKey
                )
            }
            return runs.contains(where: { $0.dayKey == tomorrowKey })
        } else {
            let shouldNotifyReady = !DailyPulseDeliveryCoordinator.hasFutureDeliveryTime(
                dayKey: todayKey,
                deliveryTimes: deliveryTimes,
                referenceDate: referenceDate,
                calendar: Calendar(identifier: .gregorian)
            )
            await generate(
                force: false,
                trigger: .delivery,
                targetDayKey: todayKey,
                notifyReadyWhenFinished: shouldNotifyReady
            )
            return runs.contains(where: { $0.dayKey == todayKey })
        }
    }

    private func generateTomorrowForDeliveryIfNeeded(
        reminderEnabled: Bool,
        referenceDate: Date
    ) async {
        guard reminderEnabled else { return }
        let tomorrowKey = Self.nextDayKey(from: referenceDate)
        guard !runs.contains(where: { $0.dayKey == tomorrowKey }) else { return }
        await generate(
            force: false,
            trigger: .delivery,
            targetDayKey: tomorrowKey
        )
    }

    public func generateIfNeeded(trigger: DailyPulseTrigger = .automatic) async {
        await waitForPersistedStateLoad()
        guard isDailyPulseEnabled else { return }
        if trigger == .automatic, !autoGenerateEnabled {
            return
        }
        let todayKey = Self.dayKey(for: Date())
        if trigger == .automatic, runs.contains(where: { $0.dayKey == todayKey }) {
            return
        }
        await generate(force: trigger == .manual, trigger: trigger)
    }

