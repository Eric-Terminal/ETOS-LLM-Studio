    private func applyPersistedState(_ state: PersistedState) {
        isApplyingPersistedState = true
        defer { isApplyingPersistedState = false }

        runs = state.runs
        feedbackHistory = state.feedbackHistory
        pendingCuration = state.pendingCuration
        tomorrowCurationText = state.pendingCuration?.text ?? ""
        externalSignals = state.externalSignals
        tasks = state.tasks

        if let settings = state.settings {
            focusText = settings.focusText
            lastViewedDayKey = settings.lastViewedDayKey
            lastDeliveryAttemptDayKey = settings.lastDeliveryAttemptDayKey
            isDailyPulseEnabled = settings.isDailyPulseEnabled
            autoGenerateEnabled = settings.autoGenerateEnabled
            includeMCPContext = settings.includeMCPContext
            includeShortcutContext = settings.includeShortcutContext
            includeRecentExternalResults = settings.includeRecentExternalResults
            includeTrendContext = settings.includeTrendContext
        }
    }

