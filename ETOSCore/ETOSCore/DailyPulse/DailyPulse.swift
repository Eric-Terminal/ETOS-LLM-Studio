        isApplyingPersistedState = true
        defer { isApplyingPersistedState = false }
        focusText = Self.textValue(forKey: Self.focusDefaultsKey, defaults: defaults, defaultValue: "")
        let storedLastViewedDayKey = Self.textValue(forKey: Self.lastViewedDayKeyDefaultsKey, defaults: defaults, defaultValue: "")
        let storedLastDeliveryAttemptDayKey = Self.textValue(forKey: Self.lastDeliveryAttemptDayKeyDefaultsKey, defaults: defaults, defaultValue: "")
        lastViewedDayKey = storedLastViewedDayKey.isEmpty ? nil : storedLastViewedDayKey
        lastDeliveryAttemptDayKey = storedLastDeliveryAttemptDayKey.isEmpty ? nil : storedLastDeliveryAttemptDayKey
        isDailyPulseEnabled = Self.boolValue(forKey: Self.dailyPulseEnabledDefaultsKey, defaults: defaults, defaultValue: true)
        autoGenerateEnabled = Self.boolValue(forKey: Self.autoGenerateDefaultsKey, defaults: defaults, defaultValue: true)
        includeMCPContext = Self.boolValue(forKey: Self.includeMCPContextDefaultsKey, defaults: defaults, defaultValue: true)
        includeShortcutContext = Self.boolValue(forKey: Self.includeShortcutContextDefaultsKey, defaults: defaults, defaultValue: true)
        includeRecentExternalResults = Self.boolValue(forKey: Self.includeRecentExternalResultsDefaultsKey, defaults: defaults, defaultValue: false)
        includeTrendContext = Self.boolValue(forKey: Self.includeTrendContextDefaultsKey, defaults: defaults, defaultValue: true)
    }

    private nonisolated static func loadAndNormalizePersistedState(
        referenceDate: Date,
        includeDatabaseSettings: Bool
    ) -> PersistedState {
        let persistedRuns = Persistence.loadDailyPulseRuns().sorted(by: { $0.generatedAt > $1.generatedAt })
        let runs = retainedRuns(from: persistedRuns, referenceDate: referenceDate)
        let feedbackHistory = Persistence.loadDailyPulseFeedbackHistory().sorted(by: { $0.createdAt > $1.createdAt })
        let storedPendingCuration = Persistence.loadDailyPulsePendingCuration()
        let todayKey = dayKey(for: referenceDate)
        let pendingCuration: DailyPulseCurationNote?
        if let storedPendingCuration, storedPendingCuration.targetDayKey < todayKey {
            pendingCuration = nil
        } else {
            pendingCuration = storedPendingCuration
        }
        let storedExternalSignals = Persistence.loadDailyPulseExternalSignals()
        let externalSignals = trimmedExternalSignals(
            storedExternalSignals,
            limit: externalSignalRetentionLimit
        )
        let storedTasks = Persistence.loadDailyPulseTasks()
        let tasks = sortedTasks(storedTasks)

        let settings: PersistedSettings?
        if includeDatabaseSettings {
            let storedLastViewedDayKey = textValue(
                forKey: lastViewedDayKeyDefaultsKey,
                defaultValue: ""
            )
            let storedLastDeliveryAttemptDayKey = textValue(
                forKey: lastDeliveryAttemptDayKeyDefaultsKey,
                defaultValue: ""
            )
            settings = PersistedSettings(
                focusText: textValue(forKey: focusDefaultsKey, defaultValue: ""),
                lastViewedDayKey: storedLastViewedDayKey.isEmpty ? nil : storedLastViewedDayKey,
                lastDeliveryAttemptDayKey: storedLastDeliveryAttemptDayKey.isEmpty ? nil : storedLastDeliveryAttemptDayKey,
                isDailyPulseEnabled: boolValue(forKey: dailyPulseEnabledDefaultsKey, defaultValue: true),
                autoGenerateEnabled: boolValue(forKey: autoGenerateDefaultsKey, defaultValue: true),
                includeMCPContext: boolValue(forKey: includeMCPContextDefaultsKey, defaultValue: true),
                includeShortcutContext: boolValue(forKey: includeShortcutContextDefaultsKey, defaultValue: true),
                includeRecentExternalResults: boolValue(forKey: includeRecentExternalResultsDefaultsKey, defaultValue: false),
                includeTrendContext: boolValue(forKey: includeTrendContextDefaultsKey, defaultValue: true)
            )
        } else {
            settings = nil
        }

        let state = PersistedState(
            runs: runs,
            feedbackHistory: feedbackHistory,
            pendingCuration: pendingCuration,
            externalSignals: externalSignals,
            tasks: tasks,
            settings: settings
        )
        guard !Task.isCancelled else { return state }

        // 规范化回写必须先于主线程应用快照完成，避免旧快照在用户后续修改后才落库。
        if runs != persistedRuns {
            Persistence.saveDailyPulseRuns(runs)
        }
        if !Task.isCancelled, pendingCuration != storedPendingCuration {
            Persistence.saveDailyPulsePendingCuration(pendingCuration)
        }
        if !Task.isCancelled, externalSignals != storedExternalSignals {
            Persistence.saveDailyPulseExternalSignals(externalSignals)
        }
        if !Task.isCancelled, tasks != storedTasks {
            Persistence.saveDailyPulseTasks(tasks)
        }

        return state
    }

